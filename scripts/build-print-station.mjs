#!/usr/bin/env node
import { copyFileSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

/**
 * Copy the Print Station into public/ so a shop can download it.
 *
 * The program's source of truth is print-station/ — it is tested there and
 * reviewed there. This copies the files a shop actually needs into
 * public/print-station/, where Next serves them, so the install line
 *
 *     irm https://rnos.in/print-station/install.ps1 | iex
 *
 * has something to fetch. Test files, and anything else a shop does not run,
 * are deliberately left behind.
 *
 * It also writes src/lib/print/bundle-files.generated.ts, which is the same
 * files as string constants. The partner download is zipped inside a route
 * handler, and a serverless function cannot read public/ off the disk — so
 * the bundle's contents have to be compiled into the function itself.
 *
 * Run: node scripts/build-print-station.mjs
 * The copy is checked by print-station/distribution.test.mjs, so it cannot
 * silently fall behind the source.
 */

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const source = join(root, "print-station");
const target = join(root, "public", "print-station");

/** What a shop downloads. Everything else in print-station/ stays behind. */
export const SHIPPED_FILES = [
  "station.mjs",
  "install.ps1",
  "README.md",
  "Start Print Station.bat",
  "Background me chalaiye.bat",
  "Background band kijiye.bat",
  "start-print-station.sh",
  "lib/config.mjs",
  "lib/api.mjs",
  "lib/worker.mjs",
  "lib/printer.mjs",
  "lib/page.mjs",
  "lib/log.mjs",
  "lib/version.mjs",
  "lib/background.ps1",
  "lib/run-hidden.vbs",
  "lib/run-hidden.ps1",
];

/**
 * What the partner download zips up.
 *
 * install.ps1 is left out on purpose: it is the fetch-from-the-web installer,
 * and a partner who already has the zip has no use for it.
 */
export const BUNDLED_FILES = SHIPPED_FILES.filter((file) => file !== "install.ps1");

export function build({ quiet = false } = {}) {
  rmSync(target, { recursive: true, force: true });
  mkdirSync(join(target, "lib"), { recursive: true });

  for (const file of SHIPPED_FILES) {
    copyFileSync(join(source, file), join(target, file));
    if (!quiet) console.log(`  ${file}`);
  }

  // A test file in public/ would be served to anybody who asked for it. It is
  // harmless, but it is also not the product, so this fails loudly instead.
  const stray = readdirSync(join(target, "lib")).filter((name) => name.includes(".test."));
  if (stray.length) throw new Error(`Test files must not be shipped: ${stray.join(", ")}`);

  writeGeneratedModule();

  const bytes = SHIPPED_FILES.reduce((total, file) => total + statSync(join(target, file)).size, 0);
  if (!quiet) console.log(`\n  ${SHIPPED_FILES.length} files, ${(bytes / 1024).toFixed(1)} KB\n`);
  return SHIPPED_FILES.length;
}

if (process.argv[1] && process.argv[1].endsWith("build-print-station.mjs")) {
  console.log("\n  Building the Print Station download...\n");
  build();
}

function writeGeneratedModule() {
  const entries = BUNDLED_FILES.map(
    (file) => `  ${JSON.stringify(file)}: ${JSON.stringify(readFileSync(join(source, file), "utf8"))},`,
  ).join("\n");

  const module = `// Generated by scripts/build-print-station.mjs — do not edit by hand.
//
// The Print Station's own source, compiled in so the partner download route
// can zip it. A serverless function does not carry public/ on its disk, so
// reading the files at request time would work locally and 500 in production.
//
// print-station/distribution.test.mjs fails if this drifts from the source.

export const PRINT_STATION_FILES: Record<string, string> = {
${entries}
};
`;

  writeFileSync(join(root, "src", "lib", "print", "bundle-files.generated.ts"), module);

  /*
    The same version the program prints, as a value the site can read.

    Kept generated rather than duplicated, so the number in the download's
    filename can never disagree with the number the program logs.
  */
  const version = /PRINT_STATION_VERSION = "([^"]+)"/.exec(
    readFileSync(join(source, "lib", "version.mjs"), "utf8"),
  )?.[1];
  if (!version) throw new Error("print-station/lib/version.mjs has no PRINT_STATION_VERSION");

  writeFileSync(
    join(root, "src", "lib", "print", "bundle-version.generated.ts"),
    `// Generated by scripts/build-print-station.mjs — do not edit by hand.\n` +
      `// Mirrors print-station/lib/version.mjs so the download's filename and\n` +
      `// the version the program logs can never disagree.\n\n` +
      `export const PRINT_STATION_VERSION = ${JSON.stringify(version)};\n`,
  );
}
