#!/usr/bin/env node
/**
 * Writes the seed migration for RNOS Digital packages from
 * src/lib/digital-plans/defaults.ts, so the shipped prices live in one file.
 *
 *   node --experimental-strip-types scripts/generate-digital-plans-seed.mjs
 *
 * The seed only inserts rows that are missing (by slug). Running it against a
 * database where an admin has already edited prices changes nothing.
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const { DEFAULT_PLANS, DEFAULT_ADDONS } = await import(path.join(root, "src/lib/digital-plans/defaults.ts"));

const q = (value) => (value === null || value === undefined ? "null" : `'${String(value).replace(/'/g, "''")}'`);
const json = (value) => `${q(JSON.stringify(value))}::jsonb`;
const bool = (value) => (value ? "true" : "false");

const out = [];
out.push("-- Generated by scripts/generate-digital-plans-seed.mjs from src/lib/digital-plans/defaults.ts.");
out.push("-- Do not edit by hand. Inserts the launch packages and add-ons only where missing.");
out.push("");

DEFAULT_ADDONS.forEach((addon, index) => {
  out.push(
    `insert into public.digital_addons (slug, name, description, price_paise, unit, price_is_starting, note, sort_order) values (${q(addon.slug)}, ${q(addon.name)}, ${q(addon.description)}, ${addon.pricePaise}, ${q(addon.unit)}, ${bool(addon.priceIsStarting)}, ${q(addon.note)}, ${index + 1}) on conflict (slug) do nothing;`,
  );
});
out.push("");

DEFAULT_PLANS.forEach((plan, index) => {
  out.push(`-- ${plan.name}`);
  out.push(
    `insert into public.digital_plans (slug, name, tagline, description, best_for, monthly_price_paise, setup_fee_paise, price_is_starting, commitment_months, is_recommended, featured_on_homepage, sort_order, limits, exclusions, maintenance, terms, faqs) values (${q(plan.slug)}, ${q(plan.name)}, ${q(plan.tagline)}, ${q(plan.description)}, ${q(plan.bestFor)}, ${plan.monthlyPricePaise}, ${plan.setupFeePaise}, ${bool(plan.priceIsStarting)}, ${plan.commitmentMonths}, ${bool(plan.isRecommended)}, ${bool(plan.featuredOnHomepage)}, ${index + 1}, ${json(plan.limits)}, ${json(plan.exclusions)}, ${q(plan.maintenance)}, ${q(plan.terms)}, ${json(plan.faqs)}) on conflict (slug) do nothing;`,
  );
  plan.features.forEach((feature, featureIndex) => {
    out.push(
      `insert into public.digital_plan_features (plan_id, feature_key, label, compare_label, value, feature_group, highlight, sort_order) select id, ${q(feature.key)}, ${q(feature.label)}, ${q(feature.compareLabel)}, ${q(feature.value)}, ${q(feature.group)}, ${bool(feature.highlight)}, ${featureIndex + 1} from public.digital_plans where slug = ${q(plan.slug)} on conflict (plan_id, feature_key) do nothing;`,
    );
  });
  plan.addonSlugs.forEach((slug, addonIndex) => {
    out.push(
      `insert into public.digital_plan_addons (plan_id, addon_id, sort_order) select p.id, a.id, ${addonIndex + 1} from public.digital_plans p, public.digital_addons a where p.slug = ${q(plan.slug)} and a.slug = ${q(slug)} on conflict do nothing;`,
    );
  });
  out.push("");
});

const target = path.join(root, "supabase/migrations/20261107120100_digital_plans_seed.sql");
writeFileSync(target, out.join("\n"));
console.log(`wrote ${path.relative(root, target)}`);
